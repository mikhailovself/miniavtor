export const isKnownFriend = (uid: string): boolean => FRIENDS.some((p) => p.id === uid);

// Род и имя известного человека по Telegram ID (для истории чата и подсказок о роде).
export function friendInfo(uid: string): { name: string; form: "он" | "она" | "?" } | null {
  const p = FRIENDS.find((x) => x.id === uid);
  if (!p) return null;
  return { name: p.call?.split(/[,(]/)[0].trim() || p.name.split(/[\/(]/)[0].trim(), form: p.form === "он" || p.form === "она" ? p.form : "?" };
}

